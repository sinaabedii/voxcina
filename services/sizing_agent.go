// Research conducts tailoring research and returns standard measurements and diagram prompt.
func (a *SizingAgent) Research(ctx context.Context, clothingType, styleNotes string) (*SizingAgentResult, error) {
	return a.ResearchWithModel(ctx, clothingType, styleNotes, "")
}

// ResearchWithModel conducts tailoring research and returns standard measurements and diagram prompt using the given model.
func (a *SizingAgent) ResearchWithModel(ctx context.Context, clothingType, styleNotes, modelOverride string) (*SizingAgentResult, error) {
	trimmedType := strings.TrimSpace(clothingType)
	if trimmedType == "" {
		return nil, fmt.Errorf("clothing type is required")
	}

	// 1. Gather context using Brave Search if available
	searchContext := a.collectSearchContext(ctx, trimmedType)

	// 2. Resolve model: explicit override > AI settings chat_model > fallback to gpt-4o-mini
	model := ResolveModel(strings.TrimSpace(modelOverride), ResolveModel(ChatModelOverride(ctx), "openai/gpt-4o-mini"))

	// 3. Generate only the garment definitions, admin measuring instructions,
	// and diagram prompt. Keeping the buyer-facing guide out of this response
	// prevents the two audiences from being blended by the model.
	definitionsPrompt := buildSizingAgentPrompt(trimmedType, styleNotes, searchContext)
	definitionsResp, err := a.openRouter.CallWithSchemaAndModel(ctx, definitionsPrompt, sizingAgentSchema(), model)
	if err != nil {
		return nil, fmt.Errorf("failed to generate sizing definitions: %w", err)
	}

	var result SizingAgentResult
	if err := json.Unmarshal([]byte(definitionsResp.Content), &result); err != nil {
		return nil, fmt.Errorf("failed to parse sizing definitions output: %w", err)
	}

	// 4. Generate the buyer guide from an explicit, lossless representation of
	// the measurements just generated. The second schema contains only the
	// guide, so it cannot accidentally replace the definitions or diagram.
	guideInput, err := json.Marshal(sizingBuyerGuideInput{
		ClothingType: trimmedType,
		StyleNotes:   strings.TrimSpace(styleNotes),
		Name:         result.Name,
		Slug:         result.Slug,
		Measurements: result.Measurements,
	})
	if err != nil {
		return nil, fmt.Errorf("failed to prepare sizing guide input: %w", err)
	}
	guidePrompt := buildBuyerFitGuidePrompt(string(guideInput))
	guideResp, err := a.openRouter.CallWithSchemaAndModel(ctx, guidePrompt, sizingBuyerGuideSchema(), model)
	if err != nil {
		return nil, fmt.Errorf("failed to generate buyer sizing guide: %w", err)
	}

	var guide sizingBuyerGuideOutput
	if err := json.Unmarshal([]byte(guideResp.Content), &guide); err != nil {
		return nil, fmt.Errorf("failed to parse buyer sizing guide output: %w", err)
	}
	result.GeneralFitGuide = guide.GeneralFitGuide

	// Maintain vector/mannequin aliases and legacy fallback logic
	if result.ImagePromptVector == "" {
		result.ImagePromptVector = result.NanoBananaPrompt
	}
	if result.NanoBananaPrompt == "" {
		result.NanoBananaPrompt = result.ImagePromptVector
	}
	if result.ImagePrompt == "" {
		result.ImagePrompt = result.ImagePromptVector
	}

	return &result, nil
}

// UpdateDiagramPromptsWithModel updates the diagram prompts for vector and mannequin styles so they describe only the provided measurements.
func (a *SizingAgent) UpdateDiagramPromptsWithModel(ctx context.Context, clothingType, styleNotes string, measurements []SizingAgentMeasurement, currentVectorPrompt, currentMannequinPrompt, modelOverride string) (*DiagramPromptsResult, error) {
	if len(measurements) == 0 {
		return nil, fmt.Errorf("at least one measurement is required")
	}

	model := ResolveModel(strings.TrimSpace(modelOverride), ResolveModel(ChatModelOverride(ctx), "openai/gpt-4o-mini"))

	prompt := buildUpdateDiagramPromptsPrompt(clothingType, styleNotes, measurements, currentVectorPrompt, currentMannequinPrompt)
	resp, err := a.openRouter.CallWithSchemaAndModel(ctx, prompt, diagramPromptsSchema(), model)
	if err == nil {
		var result DiagramPromptsResult
		if unmarshalErr := json.Unmarshal([]byte(resp.Content), &result); unmarshalErr == nil && result.ImagePromptVector != "" && result.ImagePromptMannequin != "" {
			return &result, nil
		}
	}

	// Fallback logic: construct standard prompts templates using the style blocks and measurements
	return buildFallbackDiagramPrompts(clothingType, styleNotes, measurements), nil
}

func buildFallbackDiagramPrompts(clothingType, styleNotes string, measurements []SizingAgentMeasurement) *DiagramPromptsResult {
	garmentDesc := strings.TrimSpace(clothingType)
	if garmentDesc == "" {
		garmentDesc = "garment"
	}
	if strings.TrimSpace(styleNotes) != "" {
		garmentDesc = fmt.Sprintf("%s (%s)", garmentDesc, strings.TrimSpace(styleNotes))
	}

	var vectorLines strings.Builder
	var mannequinLines strings.Builder

	for i, m := range measurements {
		label := strings.TrimSpace(m.Label)
		if label == "" {
			label = m.Key
		}
		num := i + 1
		vectorLines.WriteString(fmt.Sprintf("%d. A dimension line indicating %s, labeled \"%s\"\n", num, m.Key, label))
		mannequinLines.WriteString(fmt.Sprintf("%d. An elegant dimension line indicating %s, labeled \"%s\"\n", num, m.Key, label))
	}

	vectorPrompt := fmt.Sprintf("%s\n\nThe garment is a %s. Draw exactly %d dimension lines with these exact Persian labels:\n%s",
		sizeGuideVectorDiagramStyleBlock,
		garmentDesc,
		len(measurements),
		strings.TrimRight(vectorLines.String(), "\n"),
	)

	mannequinPrompt := fmt.Sprintf("%s\n\nThe garment is a photorealistic luxury %s with authentic tailoring details. Place exactly %d elegant dimension lines with these exact Persian labels:\n%s",
		sizeGuideMannequinDiagramStyleBlock,
		garmentDesc,
		len(measurements),
		strings.TrimRight(mannequinLines.String(), "\n"),
	)

	return &DiagramPromptsResult{
		ImagePromptVector:    vectorPrompt,
		ImagePromptMannequin: mannequinPrompt,
	}
}

// ExtrapolateSizeChartMeasurementsWithModel fills in missing measurement values across all size rows using apparel grading principles.
func (a *SizingAgent) ExtrapolateSizeChartMeasurementsWithModel(ctx context.Context, input ExtrapolateMeasurementsInput) (*ExtrapolateMeasurementsResult, error) {
	if len(input.SizeChart) == 0 {
		return nil, fmt.Errorf("at least one size chart row is required")
	}
	if len(input.Measurements) == 0 {
		return nil, fmt.Errorf("at least one measurement definition is required")
	}

	model := ResolveModel(strings.TrimSpace(input.Model), ResolveModel(ChatModelOverride(ctx), "openai/gpt-4o-mini"))

	prompt := buildExtrapolateMeasurementsPrompt(input)
	resp, err := a.openRouter.CallWithSchemaAndModel(ctx, prompt, extrapolateMeasurementsSchema(), model)

	var result ExtrapolateMeasurementsResult
	if err == nil {
		if unmarshalErr := json.Unmarshal([]byte(resp.Content), &result); unmarshalErr == nil && len(result.SizeChart) > 0 {
			// Merge protection: Ensure existing admin values are strictly preserved
			merged := mergeAndProtectSizeChart(input.SizeChart, result.SizeChart, input.Measurements)
			return &ExtrapolateMeasurementsResult{SizeChart: merged}, nil
		}
	}

	// Deterministic fallback if LLM call or parsing failed
	return fallbackExtrapolateMeasurements(input), nil
}

func mergeAndProtectSizeChart(original []models.ProductSizeMeasurement, generated []models.ProductSizeMeasurement, defs []SizingAgentMeasurement) []models.ProductSizeMeasurement {
	genMap := make(map[string]map[string]string)
	for _, row := range generated {
		sizeKey := strings.TrimSpace(strings.ToUpper(row.Size))
		if row.Values != nil {
			genMap[sizeKey] = row.Values
		}
	}

	mergedChart := make([]models.ProductSizeMeasurement, len(original))
	for i, origRow := range original {
		sizeKey := strings.TrimSpace(strings.ToUpper(origRow.Size))
		vals := make(map[string]string)
		genVals := genMap[sizeKey]

		for _, m := range defs {
			origVal := ""
			if origRow.Values != nil {
				origVal = strings.TrimSpace(origRow.Values[m.Key])
			}

			if origVal != "" {
				// Anchor: ground truth provided by admin
				vals[m.Key] = origVal
			} else if genVals != nil && strings.TrimSpace(genVals[m.Key]) != "" {
				vals[m.Key] = formatMeasurementNumber(strings.TrimSpace(genVals[m.Key]))
			}
		}

		mergedChart[i] = models.ProductSizeMeasurement{
			Size:   origRow.Size,
			Values: vals,
		}
	}

	// If any missing values remain after LLM generation, fill with deterministic fallback
	return fallbackExtrapolateChartRows(mergedChart, defs)
}

func formatMeasurementNumber(s string) string {
	s = strings.TrimSpace(s)
	// Remove trailing unit like "cm" if model added it
	s = strings.TrimSuffix(strings.TrimSuffix(s, "cm"), "CM")
	s = strings.TrimSpace(s)
	var val float64
	if _, err := fmt.Sscanf(s, "%f", &val); err == nil {
		if val == float64(int64(val)) {
			return fmt.Sprintf("%d", int64(val))
		}
		return fmt.Sprintf("%.1f", val)
	}
	return s
}

func defaultGradingDeltaForMeasurement(key, label string) float64 {
	k := strings.ToLower(key + " " + label)
	if strings.Contains(k, "shoulder") || strings.Contains(k, "شانه") ||
		strings.Contains(k, "sleeve") || strings.Contains(k, "آستین") ||
		strings.Contains(k, "neck") || strings.Contains(k, "collar") || strings.Contains(k, "یقه") ||
		strings.Contains(k, "cuff") || strings.Contains(k, "مچ") {
		return 1.0
	}
	return 2.0
}

func fallbackExtrapolateChartRows(chart []models.ProductSizeMeasurement, defs []SizingAgentMeasurement) []models.ProductSizeMeasurement {
	n := len(chart)
	if n == 0 {
		return chart
	}

	res := make([]models.ProductSizeMeasurement, n)
	for i := range chart {
		res[i] = models.ProductSizeMeasurement{
			Size:   chart[i].Size,
			Values: make(map[string]string),
		}
		if chart[i].Values != nil {
			for k, v := range chart[i].Values {
				res[i].Values[k] = strings.TrimSpace(v)
			}
		}
	}

	for _, m := range defs {
		key := m.Key
		defaultDelta := defaultGradingDeltaForMeasurement(key, m.Label)

		// Collect known numeric values and indices
		type anchor struct {
			idx int
			val float64
		}
		var anchors []anchor
		for i := 0; i < n; i++ {
			valStr := strings.TrimSpace(res[i].Values[key])
			if valStr != "" {
				var f float64
				if _, err := fmt.Sscanf(valStr, "%f", &f); err == nil {
					anchors = append(anchors, anchor{idx: i, val: f})
				}
			}
		}

		if len(anchors) == 0 {
			// No anchor exists at all; skip or keep empty
			continue
		}

		// Calculate step delta if multiple anchors exist
		stepDelta := defaultDelta
		if len(anchors) >= 2 {
			totalDelta := 0.0
			steps := 0
			for j := 0; j < len(anchors)-1; j++ {
				diff := anchors[j+1].val - anchors[j].val
				dist := anchors[j+1].idx - anchors[j].idx
				if dist > 0 {
					totalDelta += diff
					steps += dist
				}
			}
			if steps > 0 {
				calcDelta := totalDelta / float64(steps)
				if calcDelta > 0.1 && calcDelta < 10.0 {
					stepDelta = calcDelta
				}
			}
		}

		// 1. Fill backward from first anchor
		first := anchors[0]
		for i := first.idx - 1; i >= 0; i-- {
			if res[i].Values[key] == "" {
				extrapolated := first.val - float64(first.idx-i)*stepDelta
				if extrapolated < 1.0 {
					extrapolated = 1.0
				}
				res[i].Values[key] = formatMeasurementNumber(fmt.Sprintf("%.1f", extrapolated))
			}
		}

		// 2. Interpolate between anchors
		for j := 0; j < len(anchors)-1; j++ {
			a1 := anchors[j]
			a2 := anchors[j+1]
			dist := a2.idx - a1.idx
			if dist > 1 {
				gapDelta := (a2.val - a1.val) / float64(dist)
				for i := a1.idx + 1; i < a2.idx; i++ {
					if res[i].Values[key] == "" {
						extrapolated := a1.val + float64(i-a1.idx)*gapDelta
						res[i].Values[key] = formatMeasurementNumber(fmt.Sprintf("%.1f", extrapolated))
					}
				}
			}
		}

		// 3. Fill forward from last anchor
		last := anchors[len(anchors)-1]
		for i := last.idx + 1; i < n; i++ {
			if res[i].Values[key] == "" {
				extrapolated := last.val + float64(i-last.idx)*stepDelta
				res[i].Values[key] = formatMeasurementNumber(fmt.Sprintf("%.1f", extrapolated))
			}
		}
	}

	return res
}

func fallbackExtrapolateMeasurements(input ExtrapolateMeasurementsInput) *ExtrapolateMeasurementsResult {
	extrapolated := fallbackExtrapolateChartRows(input.SizeChart, input.Measurements)
	return &ExtrapolateMeasurementsResult{SizeChart: extrapolated}
}

