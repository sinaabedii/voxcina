// SizingAgentMeasurement represents one measurement definition generated by the sizing agent.
type SizingAgentMeasurement struct {
	Key                string `json:"key"`
	Label              string `json:"label"`
	BodyGuide          string `json:"body_guide"`
	FitAdvice          string `json:"fit_advice"`
	GarmentMeasurement string `json:"garment_measurement,omitempty"`
}

// SizingAgentResult holds the structured output returned by the sizing agent.
type SizingAgentResult struct {
	Name                 string                   `json:"name"`
	Slug                 string                   `json:"slug"`
	Measurements         []SizingAgentMeasurement `json:"measurements"`
	GeneralFitGuide      string                   `json:"general_fit_guide"`
	NanoBananaPrompt     string                   `json:"nano_banana_prompt"`
	ImagePromptVector    string                   `json:"image_prompt_vector,omitempty"`
	ImagePromptMannequin string                   `json:"image_prompt_mannequin,omitempty"`
	ImagePrompt          string                   `json:"image_prompt,omitempty"`
	// AdminMeasurementGuide is only used while generating a sizing type. It is
	// intentionally not copied to models.SizingType, whose public contract is
	// unchanged; the buyer guide is generated separately below.
	AdminMeasurementGuide string `json:"admin_measurement_guide,omitempty"`
}

// DiagramPromptsResult holds the updated diagram prompts for vector and mannequin styles.
type DiagramPromptsResult struct {
	ImagePromptVector    string `json:"image_prompt_vector"`
	ImagePromptMannequin string `json:"image_prompt_mannequin"`
}

// ExtrapolateMeasurementsInput represents the inputs for extrapolating missing size chart values.
type ExtrapolateMeasurementsInput struct {
	ClothingType string                          `json:"clothing_type"`
	Measurements []SizingAgentMeasurement        `json:"measurements"`
	SizeChart    []models.ProductSizeMeasurement `json:"size_chart"`
	Model        string                          `json:"model,omitempty"`
}

// ExtrapolateMeasurementsResult holds the completed size chart after extrapolation.
type ExtrapolateMeasurementsResult struct {
	SizeChart []models.ProductSizeMeasurement `json:"size_chart"`
}

// ToMeasurementDefs converts agent measurements to model measurement definitions.
func (r *SizingAgentResult) ToMeasurementDefs() []models.SizingMeasurementDef {
	defs := make([]models.SizingMeasurementDef, len(r.Measurements))
	for i, m := range r.Measurements {
		defs[i] = models.SizingMeasurementDef{
			Key:                m.Key,
			Label:              m.Label,
			BodyGuide:          m.BodyGuide,
			FitAdvice:          m.FitAdvice,
			GarmentMeasurement: m.GarmentMeasurement,
		}
	}
	return defs
}

// SizingAgent researches standard garment measurements and generates diagram prompts.
type SizingAgent struct {
	braveClient *BraveSearchClient
	openRouter  sizingStructuredClient
}

// sizingStructuredClient keeps the two-call orchestration testable without
// changing the shared OpenRouter client or any public sizing APIs.
type sizingStructuredClient interface {
	CallWithSchemaAndModel(context.Context, string, map[string]interface{}, string) (*StructuredResponse, error)
}

// NewSizingAgent creates a new sizing agent instance.
func NewSizingAgent() *SizingAgent {
	return &SizingAgent{
		braveClient: NewBraveSearchClient(),
		openRouter:  NewOpenRouterStructuredClient(),
	}
}

// GenerateSizingResearch is a convenience function that uses default clients.
