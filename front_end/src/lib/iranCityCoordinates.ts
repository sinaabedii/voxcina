const lookup = new Map<string, CityCoordinate>();
for (const [name, coord] of entries) {
  lookup.set(normalizeKey(name), coord);
}

function normalizeKey(name: string): string {
  return name
    .trim()
    .replace(/\s+/g, " ")
    .replace(/[_\-]/g, " ")
    .replace(/\s+/g, " ")
    .replace(/^استان\s+/i, "");
}

export function getCityCoordinate(
  cityName: string,
  provinceName?: string
): CityCoordinate | undefined {
  if (!cityName) return undefined;

  const direct = lookup.get(normalizeKey(cityName));
  if (direct) return direct;

  if (provinceName) {
    const province = lookup.get(normalizeKey(provinceName));
    if (province) return province;
  }

  return undefined;
}
